"""Голос писем: правила скилла human-voice, перенесённые в промпт.

Зачем. Письма рекрутёрам писались «средней моделью»: «уверен, что мой опыт
будет полезен», тройки однородных, длинные тире, вежливый финал «буду рад
обсудить». Рекрутёр читает десятки таких в день и узнаёт с первой строки.

Основа — исследование StoryScope (COLM 2026), на котором построен скилл
human-voice: AI-текст отличается не столько словами, сколько построением.
Модель проговаривает вывод, избегает конкретных названий, держит одну ровную
линию и не обращается к читателю. Чистка слов почти ничего не даёт, если
построение осталось прежним. Поэтому правила ниже сначала про построение,
потом про слова.

Скилл живёт у Claude Code, сервер его вызвать не может — отсюда перенос в
текст промпта. Исследование сделано на рассказах; для письма в пять-семь
предложений правила взяты как направления и переведены на его язык.

В самом блоке нет ни одного длинного тире, и это сделано нарочно. Первая
версия запрещала тире, но сама была написана через тире, и модель ставила
по три в каждом письме: стиль инструкции она перенимает охотнее, чем её
запреты. По той же причине в блоке нет готовых фраз: «зацепись за…» модель
повторяла буквально.

Правило про первую фразу однажды уже заставило модель соврать: требование
«первая фраза называет их задачу и твой опыт в том же» при вакансии по
речевой аналитике дало «это именно то, чем я занимался», хотя в резюме её
нет. Поэтому теперь честность прописана прямо в правиле о первой фразе.

Один блок на все генераторы (hh-письмо, телеграм-сообщение, черновик ответа
боту): письма уходят от одного человека, и голос у них должен быть один.
"""
from __future__ import annotations

import re

_VOICE_TMPL = """\
КАК ПИСАТЬ, ЧТОБЫ ЭТО ЗВУЧАЛО КАК ЧЕЛОВЕК, А НЕ КАК МОДЕЛЬ

Главное правило: честность. Факты о кандидате, его цифры, компании и проекты
бери только из резюме. Из вакансии бери только их задачу, продукт или домен.
Требования вакансии кандидату не приписывай. Ничего не придумывай ради
живости: выдуманную деталь проверят на собеседовании.

Объём и форма:
- {volume}
- Один, максимум два результата из резюме. Выбирай те, что отвечают на их
  задачу. Остальное рекрутёр увидит в резюме, пересказывать его не нужно.
- В одном предложении одна мысль. Если в предложении три цифры, это два
  предложения.

Построение:
- Первая фраза после приветствия связывает их задачу с твоим БЛИЖАЙШИМ
  настоящим опытом из резюме. Если их основной домен или продукт в резюме не
  встречается, не выдавай его за свой: назови смежный опыт как смежный.
  Писать «это то, чем я занимался» можно, только если в резюме это есть
  прямо.
- Не начинай с биографии, с того, что ты увидел вакансию, и с формулы
  «[их задача] это то, чем я занимался» или «это моя специализация». Каждое
  письмо начинай по-своему, от материала конкретной вакансии.
- Называй конкретное: компанию, продукт, цифру из резюме.
- Если в резюме нет главного требования или домена вакансии, скажи об этом
  прямо одной короткой фразой («с X не работал») и назови самое близкое из
  резюме. Не обходи пробел молча. Второстепенные пробелы не упоминай.
- Не подгоняй под вакансию характер своего опыта: если в резюме продукт для
  частных клиентов, не называй его B2B; не увеличивай масштаб, роль и размер
  команды.
- Не делай вывод за читателя. Без фраз о том, что опыт будет полезен или что
  ты подходишь.
- Последняя фраза: что конкретно готов показать или обсудить. Без формул
  вежливости.
- Не повторяй дословно слова из этой инструкции. Пиши своими словами.

Знаки и слова:
- Ни одного длинного тире. Вместо него точка, запятая, двоеточие или скобки.
- Без конструкций «не просто X, а Y» и перечислений тройками.
- Без канцелярита и штампов: «в современном мире», «важно отметить»,
  «играет ключевую роль», «является неотъемлемой частью», «уникальный»,
  «синергия», «вызовы», «комплексный подход», «стремлюсь к развитию»,
  «доброго времени суток», «заранее благодарю», «с уважением»,
  «не для галочки», «ищете человека, который».
- Предложения разной длины. Ровный ритм выдаёт шаблон.
- Не изображай живость сниженной лексикой. Живость берётся из конкретики.
- Без эмодзи, списков, жирного и markdown.
"""


def voice_rules(min_chars: int = 500, max_chars: int = 800,
                form: str = "Два-три коротких абзаца, между ними пустая строка.") -> str:
    """Правила голоса с объёмом под канал: письмо к отклику на hh длиннее
    сообщения рекрутёру в Telegram, а остальное у них общее."""
    return _VOICE_TMPL.replace("{volume}", f"{min_chars}-{max_chars} знаков. {form}")


HUMAN_VOICE = voice_rules()

# Поверхностные маркеры, которые видно без модели. Структуру (вывод, порядок,
# конкретику) так не проверить — это делает промпт; здесь только замер, чтобы
# видеть, слушается ли модель.
_TELLS = (
    "уверен, что мой опыт", "буду рад обсудить", "буду рад возможности",
    "ценным членом", "идеальным кандидатом", "в современном мире",
    "важно отметить", "стоит отметить", "ключевую роль", "неотъемлемой",
    "уникальн", "синерги", "комплексный подход", "стремлюсь к развитию",
    "доброго времени суток", "заранее благодар", "с уважением",
    "не просто ", "это не про ",
    # Любимые фразы самой модели: в пробных письмах 14.10 повторялись из
    # прогона в прогон и в потоке быстро стали бы штампом.
    "не для галочки", "ищете человека", "ищут человека",
    # Формула «их задача — это то, чем я занимался», запрещённая правилами
    # (26.10 в письме «Всё Инструменты»: «это то, что я уже проходил»).
    "это то, что я", "это то, чем я", "как раз занимался", "как раз то, чем",
    "моя специализация",
)

# Числа в письме, которых нет в источниках, почти всегда выдуманы: модель
# «оживляет» письмо процентами. Проверяем числа от двух знаков и проценты:
# однозначные («3 сервиса») в письмах обычно словами, а годы и суммы — длинные.
_NUM_RE = re.compile(r"(?<![\w.,])(\d{1,3}(?:[ \u00a0\u202f]\d{3})+|\d+(?:[.,]\d+)?)\s*(%?)")


def _norm_num(raw: str) -> str:
    return re.sub(r"[ \u00a0\u202f]", "", raw).replace(",", ".")


def invented_numbers(text: str, *sources: str) -> list[str]:
    """Числа из письма, которых нет ни в одном из источников (резюме, вакансия)."""
    have = {_norm_num(m.group(1)) for src in sources
            for m in _NUM_RE.finditer(src or "")}
    out = []
    for m in _NUM_RE.finditer(text or ""):
        num, pct = _norm_num(m.group(1)), m.group(2)
        if len(num.replace(".", "")) < 2 and not pct:
            continue
        if num not in have and (m.group(0).strip() not in out):
            out.append(m.group(0).strip())
    return out


def style_tells(text: str, max_chars: int = 900) -> list[str]:
    """Найденные шаблонные маркеры. Пусто — значит поверхность чистая.

    max_chars — потолок длины с запасом над верхней границей канала."""
    low = (text or "").lower()
    found = [t.strip() for t in _TELLS if t in low]
    # Правила запрещают длинное тире совсем: одно на письмо — уже примета
    # (26.10, «Азбука ОМНИ»: «в деньгах — например»).
    dashes = len(re.findall(r"\s—\s", text or ""))
    if dashes:
        found.append(f"длинных тире: {dashes}")
    # Длина: правила просят 500-800 знаков. 900 — с запасом, чтобы не
    # гонять повтор из-за пары лишних слов.
    if len((text or "").strip()) > max_chars:
        found.append(f"длинное: {len(text.strip())} знаков")
    return found
