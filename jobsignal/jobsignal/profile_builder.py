"""Профиль из резюме: система сама читает PDF и решает, как искать вакансии.

Зачем. До 26.10 профили заводились руками в config/profiles.yaml: имя,
подпись для письма, на какие роли целиться, запросы поиска hh. Кандидат
приносит новое резюме — и всё это надо было придумать и вписать самому.
Теперь загрузка PDF на странице «Резюме» заводит профиль: модель читает
резюме и предлагает имя, должность, фокус и запросы. Человек правит, если
надо, прямо на странице.

Правило то же, что у писем: только из резюме. Запросы поиска — названия
должностей, на которые это резюме реально подходит, а не всё подряд.
"""
from __future__ import annotations

import logging

log = logging.getLogger("jobsignal")

SYSTEM = (
    "Ты помогаешь настроить автоматический поиск работы по резюме кандидата. "
    "По тексту резюме определи его позиционирование: на какие вакансии с этим "
    "резюме имеет смысл откликаться.\n\n"
    "Верни:\n"
    "- name: короткое имя профиля, 2-5 слов, по-русски или как принято в "
    "профессии (например «Product Owner (финтех, AI)», «Лояльность и CRM»);\n"
    "- label: желаемая должность так, как она стоит в шапке резюме;\n"
    "- hh_resume_title: два-три слова из заголовка резюме, по которым его "
    "можно узнать среди других резюме того же человека на hh.ru;\n"
    "- focus: одна строка до 300 знаков: целевые роли, домены и уровень, по "
    "которым другая модель будет оценивать вакансии;\n"
    "- searches: 6-10 поисковых запросов для hh.ru, как их вводит соискатель: "
    "названия должностей и сочетания «должность + домен», по-русски и "
    "по-английски, без операторов и кавычек. Только роли, на которые резюме "
    "реально подходит по опыту и уровню.\n\n"
    "Только из резюме, ничего не додумывай. Отвечай строго одним JSON без "
    'markdown: {"name": "", "label": "", "hh_resume_title": "", "focus": "", '
    '"searches": [""]}'
)


def derive(resume_text: str) -> dict:
    """Поля профиля по тексту резюме. Бросает исключение, если модель не ответила."""
    from jobsignal.config import get_config
    from jobsignal.llm import complete_json

    if len((resume_text or "").strip()) < 300:
        raise ValueError("из PDF извлеклось слишком мало текста — это скан или "
                         "защищённый файл")
    data = complete_json(SYSTEM, f"РЕЗЮМЕ:\n{resume_text[:12000]}",
                         model=get_config().settings.anthropic_model,
                         max_tokens=900, tag="profile_from_resume")
    name = str(data.get("name") or "").strip()[:80]
    if not name:
        raise ValueError("модель не назвала профиль")
    searches = [str(s).strip()[:80] for s in (data.get("searches") or [])
                if str(s).strip()][:12]
    return {
        "name": name,
        "label": str(data.get("label") or "").strip()[:120],
        "hh_resume_title": str(data.get("hh_resume_title") or "").strip()[:80],
        "focus": str(data.get("focus") or "").strip()[:400],
        "searches": searches,
    }
