#!/bin/sh
# Ежедневная копия базы.
#
# Зачем именно сейчас. 04.10 ошибочное удаление снесло 72 настоящие отметки
# откликов. Выручила копия — но самая свежая оказалась от 10 сентября, то
# есть спасла случайность, а не устройство системы. Четыре отметки за три
# недели между копией и аварией восстановить было уже нечем.
#
# Почему `sqlite3 .backup`, а не `cp`. База работает в режиме WAL: простое
# копирование файла во время записи даёт копию без хвоста журнала, то есть
# местами битую, и узнаёшь об этом в тот единственный день, когда копия
# понадобилась. `.backup` снимает согласованный снимок на горячей базе.
#
# Хранение недели. Ошибку замечают в тот же день или на следующий; семь
# копий по ~50 МБ это 350 МБ, что при наших 2 ГБ диска терпимо, а месяц —
# уже нет.
set -eu

DB=${JOBSIGNAL_DB:-/opt/jobsignal_local/data/jobsignal.db}
DIR=${JOBSIGNAL_BACKUP_DIR:-/opt/jobsignal_local/data/backups}
KEEP=${JOBSIGNAL_BACKUP_KEEP:-7}

[ -f "$DB" ] || { echo "нет базы $DB"; exit 1; }
mkdir -p "$DIR"

OUT="$DIR/jobsignal-$(date +%Y%m%d-%H%M%S).db"
sqlite3 "$DB" ".backup '$OUT'"

# Проверяем снимок, а не верим коду возврата: копия, которую не открыть,
# это отсутствие копии, и узнать об этом надо сегодня, а не в день аварии.
if ! sqlite3 "$OUT" "pragma quick_check;" | grep -q '^ok$'; then
    echo "копия $OUT не прошла проверку целостности"
    rm -f "$OUT"
    exit 1
fi
N=$(sqlite3 "$OUT" "select count(*) from vacancies;")
echo "копия готова: $OUT ($(du -h "$OUT" | cut -f1), вакансий $N)"

# Удаляем лишние, начиная с самых старых. ls -t, а не mtime: имена содержат
# дату, но порядок берём по времени файла — так переживается ручная копия.
ls -1t "$DIR"/jobsignal-*.db 2>/dev/null | tail -n +$((KEEP + 1)) | while read -r old; do
    echo "удаляю старую копию: $old"
    rm -f "$old"
done
